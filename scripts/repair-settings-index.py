#!/usr/bin/env python3
"""Nyxus Suxyn — rebuild `quickshell/SettingsIndex.qml` from the pages.

WHY THIS EXISTS ─────────────────────────────────────────────── TRK-4171 ──

`SettingsIndex.qml` is what Settings search reads. Its own header says it is
GENERATED by `scripts/gen-settings-index.py` and guarded by `scripts/audit.sh`
gate 13w60. TRK-4137 established that neither script has ever existed in this
repo, so for its whole life this file has been a generated artifact with no
generator and no gate, drifting every time a page was edited.

TRK-4142 added `check-settings-index.py`, which REPORTS the drift and can
`--emit` entries for what is missing. It deliberately stopped short of
repairing anything, on the grounds that reproducing 527 entries byte-for-byte
was a lot of guessing. That was the right call for a byte-for-byte rebuild.
It is the wrong call for the damage, which by 2026-09-15 had reached:

    107 control strings on a page that search CANNOT see
    122 index entries naming controls that are no longer on their page

Both halves are bugs, and the second half is the worse one. An unsearchable
control is invisible; a STALE entry is a search result that leads somewhere
the control is not. The owner's standard for this build is "anything clicked
on actually works", and a hit that lands on a page with no such row fails it.

WHAT THIS DOES DIFFERENTLY FROM A REBUILD ─────────────────────────────────

It does not regenerate blind. Every existing entry is judged against the
page, and the test is deliberately WIDER than the checker's component parser:
an entry is only condemned when its label appears nowhere in the page file at
all — not in a SetRow, not in a picker option, not in any qsTr() anywhere in
it. The component parser knows four components; pages have more shapes than
that, and a narrow parser deleting entries it merely failed to understand is
exactly how this file would get worse instead of better.

    label present, sub present   keep as-is
    label present, sub stale     keep the label, re-take the sub from the
                                 page (or blank it) — the control is real,
                                 only its description rotted
    label absent                 drop; the control is gone

Then everything `page_entries()` finds that no surviving entry covers is
appended, so the missing 107 become searchable.

Output is grouped in catalogue order and, within a page, in page order —
which is what `SettingsIndex.forKey()` already promises its callers.

    scripts/repair-settings-index.py            # report what it would do
    scripts/repair-settings-index.py --write    # do it

Run `check-settings-index.py` afterwards. It is the independent check on this
script's work and should report zero drift.
"""
from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHECKER = ROOT / "scripts" / "check-settings-index.py"


def load_checker():
    """Reuse the checker's parsing rather than writing a second dialect of it.

    Two parsers for one file format is how the page and the index disagreed in
    the first place. If this import breaks, the checker changed shape and this
    script must be re-read against it — not patched around.
    """
    spec = importlib.util.spec_from_file_location("nyxus_index_checker", CHECKER)
    if spec is None or spec.loader is None:
        raise SystemExit(f"FATAL: cannot load {CHECKER}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


chk = load_checker()

# Every translated literal in a page, whatever component holds it. This is the
# wide net described in the header: the question it answers is "does this text
# exist on this page at all", which is the only question that justifies
# deleting an entry.
LITERAL_RE = re.compile(
    r"""qsTr(?:anslate)?\(\s*(?:"[^"]*"\s*,\s*)?"""
    r"""(?P<q>["'])(?P<t>(?:\\.|(?!(?P=q)).)*)(?P=q)"""
)

# One committed entry. Entries are uniform in the file: key, kind, label, and
# an optional sub that is either a qsTranslate(...) or a bare "".
ENTRY_RE = re.compile(
    r"""\{\s*key:\s*"(?P<key>[^"]+)"\s*,\s*kind:\s*"(?P<kind>[^"]+)"\s*,\s*"""
    r"""label:\s*qsTranslate\(\s*"(?P<ctx>[^"]*)"\s*,\s*"""
    r"""(?P<lq>["'])(?P<label>(?:\\.|(?!(?P=lq)).)*)(?P=lq)\s*\)\s*"""
    r"""(?:,\s*sub:\s*(?:qsTranslate\(\s*"[^"]*"\s*,\s*"""
    r"""(?P<sq>["'])(?P<sub>(?:\\.|(?!(?P=sq)).)*)(?P=sq)\s*\)|(?P<empty>\"\")))?"""
    r"""\s*\}""",
    re.S,
)


def page_literals(path: Path) -> set[str]:
    src = chk.strip_comments(path.read_text(encoding="utf-8"))
    return {chk.unescape(m.group("t")).strip() for m in LITERAL_RE.finditer(src)}


def context_for(page: str) -> str:
    return page[:-4] if page.endswith(".qml") else page


def render(key: str, kind: str, ctx: str, label: str, sub: str) -> str:
    out = [f'        {{ key: "{key}", kind: "{kind}",',
           f'          label: qsTranslate("{ctx}", "{chk.qml_escape(label)}")']
    if sub:
        out[-1] += ","
        out.append(f'          sub: qsTranslate("{ctx}", "{chk.qml_escape(sub)}") }}')
    else:
        out[-1] += ', sub: "" }'
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="rewrite the index")
    args = ap.parse_args()

    index_path = chk.INDEX
    src = index_path.read_text(encoding="utf-8")

    start = src.index("readonly property var controls")
    open_br = src.index("[", start)
    close_br = src.index("\n    ]", open_br)
    body = src[open_br + 1:close_br]

    existing: dict[str, list[tuple[str, str, str]]] = {}
    for m in ENTRY_RE.finditer(body):
        existing.setdefault(m.group("key"), []).append(
            (m.group("kind"),
             chk.unescape(m.group("label")).strip(),
             chk.unescape(m.group("sub") or "").strip()))
    before = sum(len(v) for v in existing.values())

    kept = dropped = resubbed = added = 0
    chunks: list[str] = []

    for key, page, cat_own in chk.catalogue():
        path = chk.QML / page
        if not path.exists():
            # Keep an orphan page's entries untouched: this script repairs
            # drift against a page it can read, and a missing page is a
            # different bug that deleting 20 entries would only hide.
            for kind, label, sub in existing.get(key, []):
                chunks.append(render(key, kind, context_for(page), label, sub))
                kept += 1
            continue

        lits = page_literals(path) | {s for s in cat_own if s}
        # label -> current sub, straight off the page.
        current: dict[str, tuple[str, str]] = {}
        order: list[str] = []
        for kind, label, sub in chk.page_entries(path):
            label = label.strip()
            if label not in current:
                order.append(label)
            current[label] = (kind, sub.strip())

        seen: set[str] = set()
        out: list[tuple[str, str, str]] = []

        for kind, label, sub in existing.get(key, []):
            if label not in lits:
                dropped += 1
                continue
            if sub and sub not in lits:
                sub = current.get(label, (kind, ""))[1]
                resubbed += 1
            if (label, sub) in {(l, s) for _, l, s in out}:
                continue
            out.append((kind, label, sub))
            seen.add(label)
            kept += 1

        for label in order:
            if label in seen:
                continue
            kind, sub = current[label]
            out.append((kind, label, sub))
            added += 1

        ctx = context_for(page)
        for kind, label, sub in out:
            chunks.append(render(key, kind, ctx, label, sub))

    after = len(chunks)
    print(f"  entries before : {before}")
    print(f"  kept           : {kept}")
    print(f"  dropped (stale): {dropped}")
    print(f"  subs refreshed : {resubbed}")
    print(f"  added (missing): {added}")
    print(f"  entries after  : {after}")

    if not args.write:
        print("\n  (dry run — pass --write to apply)")
        return 0

    new = src[:open_br + 1] + "\n" + ",\n".join(chunks) + src[close_br:]
    index_path.write_text(new, encoding="utf-8")
    print(f"\n  wrote {index_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
